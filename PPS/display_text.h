inline const uint8_t* cyrillicGlyph(uint32_t cp) {
  if(cp>=0x0400&&cp<=0x045F)return CYRILLIC_BITMAPS[cp-0x0400];
  if(cp==0x0490)return CYRILLIC_BITMAPS[96];
  if(cp==0x0491)return CYRILLIC_BITMAPS[97];
  return nullptr;
}

inline uint32_t nextCodepoint(const unsigned char*& p) {
  if(!*p)return 0;
  uint32_t cp=*p++;
  if(cp<0x80)return cp;
  int more=0;
  if(cp>=0xC2&&cp<=0xDF){cp&=0x1F;more=1;}
  else if(cp>=0xE0&&cp<=0xEF){cp&=0x0F;more=2;}
  else if(cp>=0xF0&&cp<=0xF4){cp&=0x07;more=3;}
  else return '?';
  const unsigned char* q=p;
  uint32_t candidate=cp;
  for(int i=0;i<more;i++){
    if(*q<0x80||*q>0xBF)return '?';
    candidate=(candidate<<6)|(*q++&0x3F);
  }
  if((more==1&&candidate<0x80)||(more==2&&candidate<0x800)||
     (more==3&&candidate<0x10000)||(candidate>=0xD800&&candidate<=0xDFFF)||
     candidate>0x10FFFF)return '?';
  p=q;
  return candidate;
}

inline uint32_t normalize(uint32_t cp) {
  if(cp=='\r')return 0;
  if(cp=='\t'||cp==0xA0)return ' ';
  if(cp=='\n')return cp;
  if(cp>=32&&cp<127)return cp;
  if(cyrillicGlyph(cp))return cp;
  if(cp==0x2013||cp==0x2014||cp==0x2212)return '-';
  if(cp==0x2018||cp==0x2019)return '\'';
  if(cp==0x201C||cp==0x201D)return '"';
  if(cp==0x2116)return '#';
  return '?';
}

inline int glyphWidth(uint32_t cp) {return cyrillicGlyph(cp)?CYRILLIC_WIDTH:6;}

inline size_t writeUtf8(char* dst,uint32_t cp) {
  if(cp<0x80){dst[0]=char(cp);return 1;}
  if(cp<0x800){dst[0]=char(0xC0|(cp>>6));dst[1]=char(0x80|(cp&63));return 2;}
  if(cp<0x10000){dst[0]=char(0xE0|(cp>>12));dst[1]=char(0x80|((cp>>6)&63));dst[2]=char(0x80|(cp&63));return 3;}
  dst[0]=char(0xF0|(cp>>18));dst[1]=char(0x80|((cp>>12)&63));
  dst[2]=char(0x80|((cp>>6)&63));dst[3]=char(0x80|(cp&63));return 4;
}

struct Line {
  char value[ROW_BYTES]{};
  ~Line(){wipe(value,sizeof(value));}
};

class Rows {
  Line visible_[5],empty_;
  size_t first_=0,count_=0;
 public:
  explicit Rows(size_t first=0):first_(first){}
  void reset(size_t first){
    for(auto& line:visible_)wipe(line.value,sizeof(line.value));
    first_=first;count_=0;
  }
  void push_back(const Line& line){
    if(count_>=first_&&count_-first_<5)visible_[count_-first_]=line;
    ++count_;
  }
  size_t size()const{return count_;}
  size_t first()const{return first_;}
  const Line& operator[](size_t absolute)const{
    return absolute>=first_&&absolute-first_<5?visible_[absolute-first_]:empty_;
  }
};

inline void append(Rows& rows,const char* first,const char* second="",const char* third="") {
  Line line;
  size_t n=0;
  int width=0;
  auto emit=[&](){
    if(n){rows.push_back(line);wipe(line.value,sizeof(line.value));n=0;width=0;}
  };
  for(const char* part:{first,second,third}){
    const unsigned char* p=reinterpret_cast<const unsigned char*>(part?part:"");
    while(*p){
      uint32_t cp=nextCodepoint(p);
      if(cp=='\n'){emit();continue;}
      cp=normalize(cp);
      if(!cp)continue;
      const int px=glyphWidth(cp);
      char encoded[4];
      const size_t nb=writeUtf8(encoded,cp);
      if(n&& (width+px>MAX_ROW_PIXELS || n+nb>=sizeof(line.value)))emit();
      if(n+nb>=sizeof(line.value))continue;
      memcpy(line.value+n,encoded,nb);
      n+=nb;line.value[n]=0;width+=px;
    }
  }
  emit();
}
